import { keepPreviousData, useQuery } from '@tanstack/react-query'
import { Info, RotateCcw, Search } from 'lucide-react'
import { useState } from 'react'
import { eventLabel } from '@/components/EventLabel'
import { Button } from '@/components/ui/button'
import { Dialog, DialogContent } from '@/components/ui/dialog'
import { Input, Select } from '@/components/ui/form'
import { Badge, Card, EmptyState, ErrorState, PageHeader, Pagination, SeverityBadge, Skeleton } from '@/components/ui/misc'
import { get } from '@/lib/api'
import type { AuditEvent, Page } from '@/lib/types'
import { useDebounced } from '@/lib/useDebounced'
import { formatDateTime } from '@/lib/utils'

const PAGE_SIZE = 25
const EMPTY = { q: '', severity: '', outcome: '', since: '', until: '' }

export function MonitoringPage() {
  const [filters, setFilters] = useState(EMPTY)
  const [page, setPage] = useState(1)
  const [selected, setSelected] = useState<AuditEvent | null>(null)
  const q = useDebounced(filters.q.trim())
  const params = { ...filters, q }

  const events = useQuery({
    queryKey: ['admin-events', params, page],
    queryFn: () => get<Page<AuditEvent>>('/admin/audit-events', { ...params, page, page_size: PAGE_SIZE }),
    placeholderData: keepPreviousData,
    refetchInterval: 30_000,
  })

  const set = (key: keyof typeof EMPTY) => (e: { target: { value: string } }) => {
    setFilters((f) => ({ ...f, [key]: e.target.value }))
    setPage(1)
  }
  const dirty = JSON.stringify(filters) !== JSON.stringify(EMPTY)

  return (
    <>
      <PageHeader
        eyebrow="Administration"
        title="Security monitoring"
        description="The append-only audit trail for all accounts. Refreshes every 30 seconds."
      />

      <div className="mb-4 flex gap-3 border border-border bg-surface px-4 py-3 text-xs text-muted">
        <Info className="mt-0.5 size-4 shrink-0 text-info" aria-hidden />
        <p>
          Events are <span className="text-fg">observations</span>, not verdicts. Severity reflects potential risk (for
          example, a lockout is high because it may indicate password guessing) and does not confirm an attack. Events
          marked <Badge className="mx-0.5">sample</Badge> were generated by the development seed command.
        </p>
      </div>

      <Card>
        <div className="grid gap-3 border-b border-border p-4 sm:grid-cols-2 lg:grid-cols-[1.5fr_repeat(4,1fr)_auto]">
          <div className="relative sm:col-span-2 lg:col-span-1">
            <Search className="pointer-events-none absolute left-3 top-1/2 size-4 -translate-y-1/2 text-subtle" aria-hidden />
            <Input value={filters.q} onChange={set('q')} placeholder="Event type, e.g. login" aria-label="Filter by event type" maxLength={64} className="pl-9" />
          </div>
          <Select value={filters.severity} onChange={set('severity')} aria-label="Severity">
            <option value="">Any severity</option>
            <option value="info">Info</option>
            <option value="low">Low</option>
            <option value="medium">Medium</option>
            <option value="high">High</option>
          </Select>
          <Select value={filters.outcome} onChange={set('outcome')} aria-label="Outcome">
            <option value="">Any outcome</option>
            <option value="success">Success</option>
            <option value="failure">Failure</option>
            <option value="ignored">Ignored</option>
          </Select>
          <Input type="date" value={filters.since} onChange={set('since')} aria-label="From date (UTC)" max={filters.until || undefined} />
          <Input type="date" value={filters.until} onChange={set('until')} aria-label="To date (UTC)" min={filters.since || undefined} />
          <Button variant="ghost" onClick={() => (setFilters(EMPTY), setPage(1))} disabled={!dirty}>
            <RotateCcw />
            Reset
          </Button>
        </div>

        {events.isPending ? (
          <div className="space-y-3 p-5">
            {Array.from({ length: 8 }, (_, i) => (
              <Skeleton key={i} className="h-7" />
            ))}
          </div>
        ) : events.isError ? (
          <ErrorState error={events.error} onRetry={() => events.refetch()} />
        ) : events.data.items.length === 0 ? (
          <EmptyState title="No events match these filters" />
        ) : (
          <>
            <div className="overflow-x-auto">
              <table className="w-full min-w-[860px] text-left text-sm">
                <thead className="border-b border-border font-mono text-[11px] uppercase tracking-wider text-subtle">
                  <tr>
                    <th className="px-5 py-2.5 font-normal">Time (local)</th>
                    <th className="px-5 py-2.5 font-normal">Severity</th>
                    <th className="px-5 py-2.5 font-normal">Event</th>
                    <th className="px-5 py-2.5 font-normal">Outcome</th>
                    <th className="px-5 py-2.5 font-normal">Actor / target</th>
                    <th className="px-5 py-2.5 font-normal">Network</th>
                  </tr>
                </thead>
                <tbody className={`divide-y divide-border ${events.isFetching ? 'opacity-80' : ''}`}>
                  {events.data.items.map((e) => (
                    <tr
                      key={e.id}
                      tabIndex={0}
                      onClick={() => setSelected(e)}
                      onKeyDown={(k) => (k.key === 'Enter' || k.key === ' ') && (k.preventDefault(), setSelected(e))}
                      className="cursor-pointer hover:bg-surface-2/60 focus-visible:bg-surface-2"
                      aria-label={`View details for ${eventLabel(e.event_type)}`}
                    >
                      <td className="whitespace-nowrap px-5 py-3 font-mono text-xs text-muted">{formatDateTime(e.created_at)}</td>
                      <td className="px-5 py-3">
                        <SeverityBadge severity={e.severity} />
                      </td>
                      <td className="px-5 py-3">
                        <span className="text-fg">{eventLabel(e.event_type)}</span>
                        {e.is_sample ? <Badge className="ml-2">sample</Badge> : null}
                        <span className="block font-mono text-[11px] text-subtle">{e.event_type}</span>
                      </td>
                      <td className="px-5 py-3 font-mono text-xs text-muted">{e.outcome}</td>
                      <td className="max-w-[220px] truncate px-5 py-3 font-mono text-xs text-muted">
                        {e.actor_email ?? e.target_email ?? '—'}
                      </td>
                      <td className="px-5 py-3 font-mono text-xs text-muted">{e.ip_prefix ?? '—'}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <Pagination page={page} pageSize={PAGE_SIZE} total={events.data.total} onPage={setPage} />
          </>
        )}
      </Card>

      <Dialog open={selected !== null} onOpenChange={(o) => !o && setSelected(null)}>
        {selected ? (
          <DialogContent title={eventLabel(selected.event_type)} description={formatDateTime(selected.created_at)} className="max-w-xl">
            <dl className="grid grid-cols-2 gap-px border border-border bg-border text-sm">
              {[
                ['Event type', selected.event_type],
                ['Severity', selected.severity],
                ['Outcome', selected.outcome],
                ['Network', selected.ip_prefix ?? '—'],
                ['Actor', selected.actor_email ?? (selected.actor_id ? 'deleted user' : 'anonymous')],
                ['Target', selected.target_email ?? '—'],
                ['Request ID', selected.request_id ?? '—'],
                ['Source', selected.is_sample ? 'Sample (seed data)' : 'Observed'],
              ].map(([k, v]) => (
                <div key={k} className="bg-surface px-3 py-2.5">
                  <dt className="font-mono text-[11px] uppercase tracking-wider text-subtle">{k}</dt>
                  <dd className="mt-0.5 break-all font-mono text-xs text-fg">{v}</dd>
                </div>
              ))}
            </dl>
            <p className="mb-1.5 mt-4 font-mono text-[11px] uppercase tracking-wider text-subtle">Metadata (sanitised)</p>
            <pre className="max-h-60 overflow-auto border border-border bg-bg p-3 font-mono text-xs text-fg">
              {JSON.stringify(selected.details, null, 2)}
            </pre>
            <p className="mt-3 break-all font-mono text-[11px] text-subtle">Event ID {selected.id}</p>
          </DialogContent>
        ) : null}
      </Dialog>
    </>
  )
}
