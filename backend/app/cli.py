"""Operational commands.

    python -m app.cli create-admin --email admin@example.com --name "Ada Admin"
    python -m app.cli seed-demo            # development only, events flagged is_sample
    python -m app.cli cleanup              # retention: purge expired sessions/tokens/old events

The admin password is read interactively (or from SS_ADMIN_PASSWORD for automation);
no default credentials exist anywhere in the code base.
"""

import argparse
import getpass
import os
import random
import sys
from datetime import timedelta

from email_validator import EmailNotValidError, validate_email
from sqlalchemy import delete, select

from app.core.config import get_settings
from app.core.database import SessionLocal, utcnow
from app.core.security import hash_password
from app.models import (
    AuditEvent,
    PasswordResetToken,
    RateLimitBucket,
    Role,
    Severity,
    User,
    UserSession,
)
from app.services.auth import normalize_email
from app.services.passwords import password_problems


def create_admin(email: str, name: str) -> int:
    try:
        # Same rules as the API's EmailStr, so the account can actually sign in.
        validate_email(email, check_deliverability=False)
    except EmailNotValidError as exc:
        print(f"Invalid email: {exc}", file=sys.stderr)
        return 1
    email = normalize_email(email)
    password = os.environ.get("SS_ADMIN_PASSWORD") or getpass.getpass("Admin password: ")
    problems = password_problems(password, email=email, name=name)
    if problems:
        print("Password rejected: " + " ".join(problems), file=sys.stderr)
        return 1
    with SessionLocal() as db:
        user = db.scalar(select(User).where(User.email == email))
        if user is None:
            user = User(email=email, name=name, password_hash=hash_password(password))
            db.add(user)
        else:
            user.password_hash = hash_password(password)
            user.password_changed_at = utcnow()
        user.role = Role.ADMIN
        db.flush()
        db.add(
            AuditEvent(
                event_type="cli.admin.create",
                severity=Severity.HIGH,
                target_user_id=user.id,
                details={"source": "cli"},
            )
        )
        db.commit()
    print(f"Administrator ready: {email}")
    return 0


_SAMPLE_EVENTS = [
    ("auth.login.success", Severity.INFO, "success"),
    ("auth.login.failure", Severity.LOW, "failure"),
    ("auth.logout", Severity.INFO, "success"),
    ("rate_limit.exceeded", Severity.MEDIUM, "failure"),
    ("auth.lockout", Severity.HIGH, "failure"),
    ("authz.denied", Severity.MEDIUM, "failure"),
    ("profile.update", Severity.INFO, "success"),
]


def seed_demo(count: int) -> int:
    if get_settings().is_production:
        print("seed-demo is disabled in production.", file=sys.stderr)
        return 1
    # Deterministic demo data; not used for anything security relevant.
    rng = random.Random(42)  # noqa: S311  # nosec B311
    now = utcnow()
    with SessionLocal() as db:
        user_ids = list(db.scalars(select(User.id).limit(50)))
        for _ in range(count):
            event_type, severity, outcome = rng.choice(_SAMPLE_EVENTS)
            db.add(
                AuditEvent(
                    event_type=event_type,
                    severity=severity,
                    outcome=outcome,
                    created_at=now - timedelta(minutes=rng.randint(0, 13 * 24 * 60)),
                    target_user_id=rng.choice(user_ids) if user_ids else None,
                    ip_prefix="203.0.113.0/24",
                    details={"note": "sample data generated by seed-demo"},
                    is_sample=True,
                )
            )
        db.commit()
    print(f"Inserted {count} sample events (is_sample=true).")
    return 0


def cleanup() -> int:
    settings = get_settings()
    now = utcnow()
    with SessionLocal() as db:
        sessions = db.execute(
            delete(UserSession).where(
                (UserSession.expires_at < now - timedelta(days=settings.session_retention_days))
                | (UserSession.revoked_at < now - timedelta(days=settings.session_retention_days))
            )
        ).rowcount
        tokens = db.execute(
            delete(PasswordResetToken).where(
                PasswordResetToken.expires_at < now - timedelta(days=1)
            )
        ).rowcount
        buckets = db.execute(
            delete(RateLimitBucket).where(RateLimitBucket.expires_at < now)
        ).rowcount
        events = db.execute(
            delete(AuditEvent).where(
                AuditEvent.created_at < now - timedelta(days=settings.audit_retention_days)
            )
        ).rowcount
        db.commit()
    print(
        f"Purged sessions={sessions} reset_tokens={tokens} "
        f"rate_limit_buckets={buckets} audit_events={events}"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m app.cli")
    sub = parser.add_subparsers(dest="command", required=True)
    admin = sub.add_parser("create-admin", help="create or promote an administrator")
    admin.add_argument("--email", required=True)
    admin.add_argument("--name", default="Administrator")
    demo = sub.add_parser("seed-demo", help="insert labelled sample audit events (dev only)")
    demo.add_argument("--count", type=int, default=120)
    sub.add_parser("cleanup", help="apply retention policies")
    args = parser.parse_args(argv)

    if args.command == "create-admin":
        return create_admin(args.email, args.name)
    if args.command == "seed-demo":
        return seed_demo(args.count)
    return cleanup()


if __name__ == "__main__":
    raise SystemExit(main())
